let seq = 0;
function p(d: Draft): Product {
  seq += 1;
  const def = DEFAULTS[d.category];
  return {
    id: `SP-${String(seq).padStart(3, "0")}`,
    sizes: d.sizes ?? def.sizes,
    care: d.care ?? def.care,
    details: d.details ?? [`Fabric: ${d.fabric}`, "Made in India by master artisans", "SARPECH zari signature"],
    ...d,
  };
}

